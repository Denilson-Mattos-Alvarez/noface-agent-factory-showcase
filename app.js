let currentLanguage = "it";
let currentStage = "discover";

function renderIcons() {
  if (window.lucide) window.lucide.createIcons();
}

function renderStage() {
  const [number, title, body, guardrail] = stageContent[currentLanguage][currentStage];
  document.querySelector("#stage-detail-number").textContent = number;
  document.querySelector("#stage-detail-title").textContent = title;
  document.querySelector("#stage-detail-body").textContent = body;
  document.querySelector("#stage-detail-guardrail").textContent = guardrail;
}

function setLanguage(language) {
  currentLanguage = language;
  document.documentElement.lang = language;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = translations[language][element.dataset.i18n];
    if (value) element.textContent = value;
  });
  document.querySelectorAll(".language-button").forEach((button) => {
    const active = button.dataset.lang === language;
    button.classList.toggle("is-active", active);
    button.setAttribute("aria-pressed", String(active));
  });
  renderStage();
  renderIcons();
}

document.querySelectorAll(".language-button").forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});

document.querySelectorAll(".pipeline-stage").forEach((button) => {
  button.addEventListener("click", () => {
    currentStage = button.dataset.stage;
    document.querySelectorAll(".pipeline-stage").forEach((stage) => {
      stage.classList.remove("is-active");
      stage.setAttribute("aria-pressed", "false");
    });
    button.classList.add("is-active");
    button.setAttribute("aria-pressed", "true");
    renderStage();
  });
});

window.addEventListener("load", renderIcons);
renderStage();
